/**
 * @file configure-environment.mjs
 * Generates the Angular production environment file from AWS CDK stack outputs.
 *
 * Usage:
 *   node scripts/configure-environment.mjs [path-to-cdk-outputs.json]
 */

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { resolve, join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);
const rootDir = resolve(__dirname, '..');

const outputsFileArg = process.argv[2];
const possibleOutputPaths = [
  outputsFileArg ? resolve(process.cwd(), outputsFileArg) : null,
  join(rootDir, 'cdk-outputs.json'),
  join(rootDir, 'infra', 'cdk-outputs.json'),
].filter(Boolean);

let outputs = null;

for (const p of possibleOutputPaths) {
  if (existsSync(p)) {
    try {
      const raw = readFileSync(p, 'utf-8');
      const json = JSON.parse(raw);
      // CDK outputs are keyed by stack name (e.g. DriveLiteStack)
      outputs = json.DriveLiteStack || json[Object.keys(json)[0]] || {};
      console.log(` Loaded CDK stack outputs from: ${p}`);
      break;
    } catch (err) {
      console.warn(`⚠️ Failed to parse outputs from ${p}:`, err.message);
    }
  }
}

// Fallback: Check if environment.aws.ts exists for local dev fallback
const envAwsPath = join(rootDir, 'frontend', 'src', 'environments', 'environment.aws.ts');
let fallbackAwsEnv = null;
if (!outputs && existsSync(envAwsPath)) {
  try {
    const content = readFileSync(envAwsPath, 'utf-8');
    const extract = (key) => {
      const m = content.match(new RegExp(`${key}:\\s*['"]([^'"]*)['"]`));
      return m ? m[1] : '';
    };
    fallbackAwsEnv = {
      ApiUrl: extract('apiUrl'),
      UserPoolId: extract('cognitoUserPoolId'),
      UserPoolClientId: extract('cognitoClientId'),
      BucketName: extract('s3Bucket'),
      HostingBucketName: extract('hostingBucket'),
      WebsiteUrl: extract('websiteUrl'),
      CloudFrontUrl: extract('websiteUrl'),
    };
    console.log('ℹ️ Using fallback values from environment.aws.ts');
    outputs = fallbackAwsEnv;
  } catch {
    // Ignore fallback parse error
  }
}

if (!outputs) {
  console.error('❌ Error: No CDK stack outputs or fallback environment found.');
  console.error('Please run CDK deploy with `--outputs-file cdk-outputs.json` first.');
  process.exit(1);
}

const apiUrl = outputs.ApiUrl || process.env.API_URL || '';
const userPoolId = outputs.UserPoolId || process.env.COGNITO_USER_POOL_ID || '';
const userPoolClientId = outputs.UserPoolClientId || process.env.COGNITO_CLIENT_ID || '';
const cognitoEndpoint = outputs.CognitoEndpoint || '';
const cognitoAuthDomain = outputs.CognitoAuthDomain || '';
const s3Bucket = outputs.BucketName || process.env.S3_BUCKET || '';
const hostingBucket = outputs.HostingBucketName || process.env.HOSTING_BUCKET || '';
const websiteUrl = outputs.WebsiteUrl || outputs.CloudFrontUrl || '';
const s3Region = outputs.S3Region || process.env.AWS_REGION || 'us-east-1';

const prodEnvContent = `/**
 * Production environment configuration.
 * Automatically generated by scripts/configure-environment.mjs at build/deploy time.
 * DO NOT EDIT DIRECTLY.
 */
export const environment = {
  production: true,
  apiUrl: '${apiUrl}',
  cognitoEndpoint: '${cognitoEndpoint}',
  cognitoUserPoolId: '${userPoolId}',
  cognitoClientId: '${userPoolClientId}',
  cognitoAuthDomain: '${cognitoAuthDomain}',
  s3Bucket: '${s3Bucket}',
  hostingBucket: '${hostingBucket}',
  websiteUrl: '${websiteUrl}',
  s3Region: '${s3Region}',
};
`;

const prodEnvPath = join(rootDir, 'frontend', 'src', 'environments', 'environment.prod.ts');
writeFileSync(prodEnvPath, prodEnvContent, 'utf-8');
console.log(`✨ Generated Angular production environment file at: ${prodEnvPath}`);
console.log(`   - API URL: ${apiUrl || '(empty)'}`);
console.log(`   - User Pool ID: ${userPoolId || '(empty)'}`);
console.log(`   - Client ID: ${userPoolClientId || '(empty)'}`);
console.log(`   - Files S3 Bucket: ${s3Bucket || '(empty)'}`);
console.log(`   - Hosting S3 Bucket: ${hostingBucket || '(empty)'}`);
console.log(`   - Website URL: ${websiteUrl || '(empty)'}`);
